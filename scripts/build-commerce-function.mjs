import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url),target=new URL('base44/functions/ssk-commerce-v10/lib/',root);
await mkdir(target,{recursive:true});
const modules={
 'store.js':'commerce/backend/store.js','service.js':'commerce/backend/service.js','ccv.js':'commerce/backend/ccv.js',
 'commerce-contract.js':'glove_builder/customiser/commerce-contract.js',
 'commerce-catalog.js':'glove_builder/customiser/commerce-catalog.js',
 'commerce-pricing.js':'glove_builder/customiser/commerce-pricing.js',
 'glove-catalog.js':'glove_builder/customiser/glove-catalog.js','refcode.js':'glove_builder/customiser/refcode.js'};
for(const [name,path] of Object.entries(modules)) {
 const source=(await readFile(new URL(path,root),'utf8')).replaceAll('../../glove_builder/customiser/','./');
 const generated='// Generated by scripts/build-commerce-function.mjs. Edit the canonical source.\n'+source;
 if(process.argv.includes('--check')){if(await readFile(new URL(name,target),'utf8')!==generated)throw Error('Stale function dependency: '+name);}
 else await writeFile(new URL(name,target),generated);
}
